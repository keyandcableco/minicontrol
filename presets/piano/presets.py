PRESETS = []


def preset(name, hue, blurb, shows, controls, *parts, play=None):
    PRESETS.append(dict(name=name, hue=hue, blurb=blurb, shows=shows, controls=controls, play=play or [],
                        settings=merge({20: hue}, performance(), *parts)))


def piano_chords(decay=3500, sustain=0.6, release=400, filt=2600, amp=0.24, reverb=0.25, ensemble=0,
                 crunch=0.0, crunch_type=0, octave=2):
    """the sampled piano on the chord buttons, voice-led like a pianist's left hand, a changed chord struck
    again (21; under brothers each block the harp picks is struck, firmware 88). The levels start
    from the measured piano presets (Fortepiano Sonata, Honky-Tonk, Late Night Duo)"""
    return merge(chord_sample(PIANO), chord_env(1, 0, decay, sustain, release),
                 chord_filter(filt, 0.3, 0.7), chord_trem(), chord_vib(), chord_delay(),
                 chord_out(300, 0.8, 1.0, 1.0, amp), chord_fx(reverb, crunch, crunch_type, ensemble),
                 {120: 2, 198: octave, 111: 1, 112: 7, 21: 1})


def piano_harp(decay=3500, sustain=0.6, release=500, filt=2000, amp=0.52, reverb=0.25, spread=40, touch=80,
               strum=30, mode=8, octave=2):
    """the sampled piano on the harp, the right hand: the scale of each chord, louder as it's struck harder"""
    return merge(harp_sample(PIANO), harp_env(1, 0, decay, sustain, release),
                 harp_filter(filt, 1.5, 0.7), harp_trem(), harp_vib(), harp_delay(), harp_transient(0.0),
                 harp_out(300, 0.85, 1.0, 1.0, amp), harp_fx(reverb, spread=spread),
                 {36: mode, 99: octave, 252: touch, 263: strum})


def upright_bass(level=0.73):
    """the chord's bass note on the sampled upright bass (firmware 80), the piano above it"""
    return {270: note_voice(UPRIGHT), **chord_notes(level, 0.45, 0.45, 0.45)}


