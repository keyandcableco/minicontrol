PRESETS = []

CONTROLS = {
    "mod knob": "the drums' level",
    "modifier + mod knob": "swing, in rhythm mode: straight in the middle, a triplet shuffle to the right",
    "modifier + harp knob": "the drums' room",
    "modifier + chord knob": "the chords' tone",
    "double tap": "the looper: a bar of clicks, two bars recorded onto the sixteenths, played back",
}


def preset(name, hue, blurb, shows, controls, *parts, play=None):
    PRESETS.append(dict(name=name, hue=hue, blurb=blurb, shows=shows, controls=dict(CONTROLS, **controls),
                        play=play or [], settings=merge({20: hue}, performance(), *parts)))


def pads(kit, groove, bpm, level=65, humanize=10, reverb=15, laya=0, swing=1.0, groove_b=0, chord_tone=None,
         press=3, alt=(SWING, 33)):
    """the plate as the kit's pads and seams, the groove under them in rhythm mode, and the set's controls;
    press, how many semitones a struck skin rises under a pressing finger (drum press), and a finger resting
    on a pad holds its voice out of the groove (pads mute the groove). alt is what modifier + mod knob turns:
    the swing, a third either side of the bank's own (1.0, straight: 0.67 to 1.33, a triplet shuffle), or
    for a groove with nothing to swing (written in triplets, or a theka a bol a beat) the room's size"""
    return merge(
        drums(groove, kit=kit, level=level, humanize=humanize, groove_b=groove_b, harp=1, reverb=reverb, laya=laya),
        {DRUM_SEAMS: 1, 340: 0, 252: 80, DRUM_PRESS: press, PADS_MUTE: 1, MELODIC_PADS: 0},
        style(11, bpm, bass=HOLD, chords=HOLD, swing=swing),
        sections(ending=1, fill=1, count_in=1),
        looper(quantize=3, count_in=1, click=2, click_level=40, length=2),
        {249: 0, 325: 0, 303: 0, 307: 0},
        knobs(chord_alt=(chord_tone or 143, 100), harp_alt=(378, 100), mod=(338, 100), mod_alt=alt),
        double_tap((LOOPER, 6)))


