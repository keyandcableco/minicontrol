"""Bent Board: twelve instruments for the bent board (harp plate 5, firmware 121), the full-face plate whose
touch areas bend the sound, that play just as well on any other plate. Each is an instrument from another set,
borrowed as it is, with the bends wired in twice over:

- on every plate, Circuit Bent's controls: the mod knob is pitch drop, the modifier with the chord, harp and
  mod knobs bitcrush, clock bend and stutter, and a double tap then the modifier held starves the supply
  while it is held; hover stays the instrument's own;
- on the bent board, the bend rail's five points are the five bends, as deep as each is pressed, and the palm
  pad and the thumb ribbon each do one thing for that instrument, different in every bank; and the areas
  played together (bent board options, 486): EVERYDAY in most banks, SECOND_KNOB where the thumb shaping a
  bend suits the instrument better than catching it, and the palm hold in one bank to try.

The parts are in ../kit.py.
"""
