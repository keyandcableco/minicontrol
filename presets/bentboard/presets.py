def bends(drop_range=12, sag=150, starve=0, crush=0, crush_mode=BITS_AND_RATE, clock_faster=0, sync=0,
          shortest=25, drums_stutter=0, interact=0, spring=1000):
    """how the bank's bends behave, and what is bent before a hand touches anything"""
    return {PITCH_DROP: 0, PITCH_DROP_RANGE: drop_range, PITCH_DROP_SAG: sag, STARVE: starve, CRUSH: crush,
            CRUSH_MODE: crush_mode, CLOCK_BEND: 0, CLOCK_FASTER: clock_faster, STUTTER: 0, STUTTER_SYNC: sync,
            STUTTER_SHORTEST: shortest, STUTTER_DRUMS: drums_stutter, INTERACT: interact,
            SPRING_BACK: SPRINGS_PLAYED, SPRING_TIME: spring, STUTTER_REFRESH: 2000}


def wired():
    """the set's controls on every plate: the knobs as Circuit Bent has them, the double tap held a brown-out
    (hover stays the borrowed instrument's own)"""
    return merge(knobs(chord_alt=(CRUSH, 100), harp_alt=(CLOCK_BEND, 100), mod=(PITCH_DROP, 100),
                       mod_alt=(STUTTER, 100)),
                 hover_alt(0, 0), double_tap((STARVE, 80), hold=1), {117: 0},
                 # each knob's alternate remembered at the bottom: a bank load puts a knob's alternate at the
                 # value it remembers (4-6), and a bend there loads bent (Circuit Bent once loaded silent so)
                 {4: 0, 5: 0, 6: 0})


def board(set_name, base, name, hue, blurb, shows, how, palm, ribbon, *parts, play=None, options=EVERYDAY, **kw):
    """an instrument from another set: its sound as it is there, the set's controls wired over it, the bent
    board's palm pad and thumb ribbon given their jobs (each (target, value)) and its options, then the bank's
    own bends"""
    p = borrow(set_name, base)
    settings = merge(p["settings"], {20: hue}, wired(), bent_board(palm=palm, ribbon=ribbon, options=options),
                     bends(**kw), *parts)
    PRESETS.append(dict(name=name, hue=hue, blurb=blurb, shows=shows, controls=merge(CONTROLS, how),
                        play=play or [], settings=settings, **{"from": f"{set_name}: {base}"}))


