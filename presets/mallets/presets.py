PRESETS = []


def preset(name, hue, blurb, shows, controls, *parts, play=None):
    PRESETS.append(dict(name=name, hue=hue, blurb=blurb, shows=shows, controls=controls, play=play or [],
                        settings=merge({20: hue}, performance(), *parts)))


def struck_harp(voice, decay=1800, sustain=0.0, release=900, filt=2000, amp=0.6, reverb=0.3, spread=30,
                pattern=0, crunch=0.0, crunch_type=0):
    """a sampled struck or plucked voice on the harp: its strike, and its ring as long as decay lets it"""
    return merge(harp_sample(voice), harp_env(1, 0, decay, sustain, release),
                 harp_filter(filt, 1.0, 0.7), harp_trem(), harp_vib(), harp_delay(),
                 harp_transient(0.0), harp_out(300, 0.85, 1.0, 1.0, amp),
                 harp_fx(reverb, crunch=crunch, crunch_type=crunch_type, spread=spread, pattern=pattern))


def struck_chords(voice, decay=1800, sustain=0.0, release=900, filt=4000, amp=0.5, reverb=0.3, crunch=0.0,
                  crunch_type=0, ensemble=0):
    """the same voice on the chord buttons (no vibrato: a sampled voice takes none)"""
    return merge(chord_sample(voice), chord_env(1, 0, decay, sustain, release),
                 chord_filter(filt, 0.3, 0.7), chord_trem(), chord_vib(), chord_delay(),
                 chord_out(250, 0.85, 1.0, 1.0, amp),
                 chord_fx(reverb, crunch=crunch, crunch_type=crunch_type, ensemble=ensemble))


def sound_hole(closed=350):
    """hover as a hand cupped over a kalimba's sound hole: the harp's filter closes as the hand comes down"""
    return hover(49, closed, 8)


