PRESETS = []


def preset(name, hue, blurb, shows, controls, *parts, play=None):
    PRESETS.append(dict(name=name, hue=hue, blurb=blurb, shows=shows, controls=controls, play=play or [],
                        settings=merge({20: hue}, performance(), *parts)))


def ep_chords(decay=4500, sustain=0.25, release=500, filt=3000, amp=0.45, reverb=0.3, ensemble=0, drive=0.0):
    """the sampled electric piano on the chord buttons: the envelope lets it ring as long as decay says"""
    return merge(chord_sample(EPIANO), chord_env(1, 0, decay, sustain, release),
                 chord_filter(filt, 0.3, 0.7), chord_trem(), chord_vib(), chord_delay(),
                 chord_out(250, 0.85, 1.0, 1.0, amp), chord_fx(reverb, crunch=drive, ensemble=ensemble))


def ep_harp(decay=4000, sustain=0.3, release=600, filt=2000, amp=0.55, reverb=0.3, spread=40, pattern=0):
    return merge(harp_sample(EPIANO), harp_env(1, 0, decay, sustain, release),
                 harp_filter(filt, 1.2, 0.7), harp_trem(), harp_vib(), harp_delay(),
                 harp_transient(0.0), harp_out(300, 0.85, 1.0, 1.0, amp), harp_fx(reverb, spread=spread, pattern=pattern))


