PRESETS = []


def preset(name, hue, blurb, shows, controls, *parts, play=None):
    PRESETS.append(dict(name=name, hue=hue, blurb=blurb, shows=shows, controls=controls, play=play or [],
                        settings=merge({20: hue}, performance(), *parts)))


def sub_under(pad, pad_level=0.4, sub_level=0.85):
    """a sine sub an octave under the bass note on the chord voices' own oscillators, the other three a
    sampled pad"""
    return merge(chord_osc(0.22, SINE, 0.5, 0.04, TRI, 1.0), chord_sample(pad), {270: NOTE_OWN},
                 chord_notes(sub_level, pad_level, pad_level, pad_level))


def bass_only(level=0.9):
    """the bass note alone: the other three chord voices silent"""
    return chord_notes(level, 0.0, 0.0, 0.0)


