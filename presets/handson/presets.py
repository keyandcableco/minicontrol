PRESETS = []


def hands_on(set_name, base, name, hue, blurb, shows, rail, palm, ribbon, *parts, play=None, changed=None):
    """an instrument from another set, as it is there, with the bent board's seven areas on settings of its
    own: rail, five (target, value, what it does) left to right; palm and ribbon, (target, value, what it does);
    parts, settings of the preset's own changed (a rate under a depth, an echo's time). What an area's setting
    needs to be heard (NEEDS) is filled in where the preset leaves it at 0"""
    p = borrow(set_name, base)
    targets, values, rail_how = zip(*rail)
    settings = merge(p["settings"], {20: hue}, *parts)
    for t, v in list(zip(targets, values)) + [palm[:2], ribbon[:2]]:
        for a, need in NEEDS.get(t, {}).items():
            if not settings.get(a):
                settings[a] = need
        assert t not in (C_TREM, H_TREM) or v <= TREMOLO_MOST, f"{name}: tremolo {v} over {TREMOLO_MOST}"
    settings.update(bent_board(rail=values, rail_targets=targets, palm=palm[:2], ribbon=ribbon[:2], options=0))
    how = {"bend rail (bent board)": ", ".join(rail_how) + ", left to right, as deep as each dot is pressed",
           "palm pad (bent board)": palm[2], "thumb ribbon (bent board)": ribbon[2]}
    out = dict(name=name, hue=hue, blurb=blurb, shows=shows, controls=how, play=play or [], settings=settings,
               **{"from": f"{set_name}: {base}"})
    if changed:
        out["changed"] = changed
    PRESETS.append(out)
    return out


