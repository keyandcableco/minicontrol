def preset(name, hue, blurb, shows, controls, *parts, play=None):
    PRESETS.append(dict(name=name, hue=hue, blurb=blurb, shows=shows, controls=controls, play=play or [],
                        settings=merge({20: hue}, performance(), *parts)))


def bend_scoop(depth=0.94, ms=60):
    """the chords start a little under the pitch and scoop up to it (the pitch bend envelope, 170-175): a
    brass player's attack. Intensity 1 so the envelope is heard; the vibrato itself stays at 0"""
    return merge(chord_vib(), {170: depth, 171: 1, 172: 1, 173: ms, 175: 1.0})


