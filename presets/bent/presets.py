PRESETS = []

CONTROLS = {
    "mod knob": "pitch drop: the whole instrument sags down, deeper as the knob goes up",
    "hover": "voltage starve: wobble, fuzz, brown-outs and crackle, harder as the hand comes closer",
    "modifier + chord knob": "bitcrush",
    "modifier + harp knob": "clock bend",
    "modifier + mod knob": "stutter: a slice repeating, shorter as the knob goes up",
}


def bends(drop_range=12, sag=150, starve=0, crush=0, crush_mode=BITS_AND_RATE, clock_faster=0, sync=0,
          shortest=25, drums_stutter=0, interact=0, spring=1000):
    """how the bank's bends behave, and what is bent before a hand touches anything; the controls are the
    set's own (wired)"""
    return {PITCH_DROP: 0, PITCH_DROP_RANGE: drop_range, PITCH_DROP_SAG: sag, STARVE: starve, CRUSH: crush,
            CRUSH_MODE: crush_mode, CLOCK_BEND: 0, CLOCK_FASTER: clock_faster, STUTTER: 0, STUTTER_SYNC: sync,
            STUTTER_SHORTEST: shortest, STUTTER_DRUMS: drums_stutter, INTERACT: interact,
            SPRING_BACK: SPRINGS_PLAYED, SPRING_TIME: spring, STUTTER_REFRESH: 2000}


def wired(interact):
    """the set's controls: the same in every bank (the borrowed instrument's own knobs, hover and double
    tap give way to them)"""
    return merge(knobs(chord_alt=(CRUSH, 100), harp_alt=(CLOCK_BEND, 100), mod=(PITCH_DROP, 100),
                       mod_alt=(STUTTER, 100)),
                 hover(STARVE, 100, 7), hover_alt(0, 0),
                 double_tap((INTERACT, 0 if interact else 100)), {117: 0},
                 # each knob's alternate remembered at the bottom: a bank load puts a knob's alternate at the
                 # value it remembers (4-6), and these were the middle, so every bank loaded with the crush,
                 # the clock bend and a stutter (looping the silence of the load) at about half
                 {4: 0, 5: 0, 6: 0})


def bent(set_name, base, name, hue, blurb, shows, how, *parts, play=None, interact=0, **kw):
    """an instrument from another set, bent: its sound as it is there, the set's controls wired over it,
    then the bank's own bends"""
    p = borrow(set_name, base)
    settings = merge(p["settings"], {20: hue}, wired(interact), bends(interact=interact, **kw), *parts)
    double = ("the bends let go of one another (they interact here from the start); again, back"
              if interact else "the bends interact: the pitch drop drags the beat and grits the sample "
                               "rate, the starve stumbles it and eats bits; again, each on its own")
    PRESETS.append(dict(name=name, hue=hue, blurb=blurb, shows=shows,
                        controls=merge(CONTROLS, {"double tap": double}, how),
                        play=play or [], settings=settings, **{"from": f"{set_name}: {base}"}))


