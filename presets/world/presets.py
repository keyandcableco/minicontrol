PRESETS = []


def preset(name, hue, blurb, shows, controls, *parts, play=None):
    PRESETS.append(dict(name=name, hue=hue, blurb=blurb, shows=shows, controls=controls, play=play or [],
                        settings=merge({20: hue}, performance(), *parts)))


def accordion(amp=0.8, ensemble=20):
    """the sampled accordion (firmware 80), its musette reeds beating in the recording; the ensemble widens them"""
    return merge(chord_sample(ACCORDION),
                 chord_env(30, 0, 300, 0.95, 150), chord_filter(2200, 0.3, 0.9),
                 chord_trem(), chord_vib(), chord_delay(),
                 chord_out(300, 0.8, 1.0, 1.0, amp), chord_fx(0.25, ensemble=ensemble))


