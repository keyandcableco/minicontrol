"""List the bank sets the page offers, in banksets.json.

Usage: python3 generate_banksets.py

A bank set is twelve presets in a minichord backup file (the format banks.js and Sound Lab
write), with an optional title, author and description, and a blurb for each bank. They come
from two places:

  - presets/<set>/<set>.backup.json, built by presets/build.py, whose title is presets.py's
    TITLE and whose description and blurbs come from the README.md it writes beside it;
  - banksets/*.json, sets players have shared (uploaded on GitHub and merged), each carrying
    its own title, author and description.

A shared file is untrusted: one that isn't a sound backup is reported and left out. The deploy
runs this before publishing, so a merged set appears without anyone running it by hand; run it
locally to see a new set on a page served from this folder.
"""
import json
import os
import re
import sys

OUT = 'banksets.json'
OURS = 'Key & Cable'
BANK_COUNT = 12
MAX_ADDRESS = 512
LIMITS = {'title': 60, 'author': 40, 'description': 600, 'blurb': 300, 'name': 24}


def clip(text, limit):
    text = re.sub(r'\s+', ' ', str(text or '')).strip()
    return text if len(text) <= limit else text[:limit - 1].rstrip() + '…'


def plain(markdown):
    """A README paragraph as plain text: no links, emphasis or code marks."""
    text = re.sub(r'\[([^\]]*)\]\([^)]*\)', r'\1', markdown)
    return re.sub(r'[*_`]', '', text)


def problem(data):
    """Why a backup file can't be offered, or None. As banks.js's backupProblem."""
    if not isinstance(data, dict) or not data.get('minichord_backup'):
        return "isn't a minichord backup"
    banks = data.get('banks')
    if not isinstance(banks, list) or not banks or len(banks) > BANK_COUNT:
        return 'has no banks, or more than twelve'
    seen = set()
    for entry in banks:
        if not isinstance(entry, dict):
            return 'has a damaged bank'
        bank = entry.get('bank')
        if not isinstance(bank, int) or not 0 <= bank < BANK_COUNT or bank in seen:
            return "has bank numbers that don't make sense"
        seen.add(bank)
        values = entry.get('values')
        if not isinstance(values, list) or len(values) > MAX_ADDRESS or not all(
                v is None or (isinstance(v, int) and not isinstance(v, bool) and 0 <= v < 16384) for v in values):
            return f'has a damaged bank {bank + 1}'
        if entry.get('name') is not None and not isinstance(entry['name'], str):
            return 'has damaged bank names'
    return None


def presets_of(data, blurbs=None):
    """What the page shows of each bank before the file is fetched: name, colour, blurb."""
    out = []
    for i, entry in enumerate(sorted(data['banks'], key=lambda e: e['bank'])):
        values = entry['values']
        hue = values[20] if len(values) > 20 and isinstance(values[20], int) else None
        blurb = entry.get('blurb') or (blurbs[i] if blurbs and i < len(blurbs) else '')
        out.append({'bank': entry['bank'], 'name': clip(entry.get('name') or f'bank {entry["bank"] + 1}', LIMITS['name']),
                    'hue': hue, 'blurb': clip(blurb, LIMITS['blurb'])})
    return out


def our_sets():
    """The sets presets/build.py makes, one folder each."""
    sets = []
    if not os.path.isdir('presets'):
        return sets
    for name in sorted(os.listdir('presets')):
        folder = os.path.join('presets', name)
        path = os.path.join(folder, f'{name}.backup.json')
        if not os.path.isfile(path):
            continue
        with open(path) as f:
            data = json.load(f)
        why = problem(data)
        if why:
            print(f'{path} {why}: left out', file=sys.stderr)
            continue
        title, description, blurbs = name, '', []
        source = os.path.join(folder, 'presets.py')
        if os.path.isfile(source):
            found = re.search(r'^TITLE\s*=\s*["\'](.+?)["\']\s*$', open(source).read(), re.M)
            if found:
                title = found.group(1)
        readme = os.path.join(folder, 'README.md')
        if os.path.isfile(readme):
            paragraphs = [p.strip() for p in open(readme).read().split('\n\n')]
            # the paragraph under the title, without the note on how it was made
            if len(paragraphs) > 1:
                description = ' '.join(s for s in re.split(r'(?<=[.;])\s+', plain(paragraphs[1]))
                                       if 'Generated by' not in s and 'edit those' not in s)
            # each preset's heading ("## 3. Jazz Piano") and the paragraph after it
            for i, p in enumerate(paragraphs):
                if re.match(r'^## \d+\. ', p) and i + 1 < len(paragraphs):
                    blurbs.append(plain(paragraphs[i + 1]))
        sets.append({'id': name, 'title': clip(title, LIMITS['title']), 'author': OURS,
                     'description': clip(description, LIMITS['description']),
                     'firmware': data.get('firmware_version'), 'file': path.replace(os.sep, '/'),
                     'presets': presets_of(data, blurbs)})
    return sets


def shared_sets():
    """The sets players have shared, a file each in banksets/."""
    sets = []
    if not os.path.isdir('banksets'):
        return sets
    for file in sorted(os.listdir('banksets')):
        if not file.endswith('.json'):
            continue
        path = os.path.join('banksets', file)
        try:
            with open(path) as f:
                data = json.load(f)
        except (OSError, ValueError) as e:
            print(f'{path} is not JSON ({e}): left out', file=sys.stderr)
            continue
        why = problem(data)
        if why:
            print(f'{path} {why}: left out', file=sys.stderr)
            continue
        sets.append({'id': 'shared-' + re.sub(r'[^a-z0-9]+', '-', file[:-5].lower()).strip('-'),
                     'title': clip(data.get('title') or file[:-5], LIMITS['title']),
                     'author': clip(data.get('author') or 'a player', LIMITS['author']),
                     'description': clip(data.get('description'), LIMITS['description']),
                     'firmware': data.get('firmware_version') if isinstance(data.get('firmware_version'), int) else None,
                     'file': path.replace(os.sep, '/'), 'shared': True,
                     'presets': presets_of(data)})
    return sets


def main():
    sets = our_sets() + shared_sets()
    with open(OUT, 'w') as f:
        json.dump({'banksets': sets}, f, indent=1, ensure_ascii=False)
        f.write('\n')
    print(f'Listed {len(sets)} bank sets in {OUT}')


if __name__ == '__main__':
    main()
